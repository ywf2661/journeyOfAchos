// 한 줄씩 이어지는 대사 묶음. 노드 id는 id, id.1, id.2 … 이고, 마지막 줄에 last의 필드를 덧붙인다.
function chain(id, lines, last = {}) {
  const nodes = {};
  lines.forEach(([who, text], i) => {
    const isLast = i === lines.length - 1;
    nodes[i ? `${id}.${i}` : id] = { who, text, ...(isLast ? last : { next: `${id}.${i + 1}` }) };
  });
  return nodes;
}

